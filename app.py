# 3. SESSION STATE INITIALIZATION
# ==========================================
# We use session state to remember variables across app interactions (button clicks)
if "extracted_text" not in st.session_state:
    st.session_state.extracted_text = ""
if "chat_history" not in st.session_state:
    st.session_state.chat_history = []
if "chat_session" not in st.session_state:
    st.session_state.chat_session = None
if "quiz_data" not in st.session_state:
    st.session_state.quiz_data = None
if "quiz_submitted" not in st.session_state:
    st.session_state.quiz_submitted = False

# ==========================================
# 4. SIDEBAR (Configuration & Upload)
# ==========================================
with st.sidebar:
    st.title("🎓 Settings")

    # User inputs their Gemini API Key here
    api_key = st.text_input("Enter Gemini API Key", type="password")

    st.markdown("---")
    st.subheader("📁 Upload Notes")
    uploaded_file = st.file_uploader("Upload PDF or PPTX", type=["pdf", "pptx"])

    if st.button("Process Document"):
        if not api_key:
            st.error("Please enter your Gemini API Key first.")
        elif not uploaded_file:
            st.error("Please upload a file to process.")
        else:
            with st.spinner("Extracting text..."):
                # Extract text based on file type
                if uploaded_file.name.endswith(".pdf"):
                    text = extract_text_from_pdf(uploaded_file)
                elif uploaded_file.name.endswith(".pptx"):
                    text = extract_text_from_ppt(uploaded_file)

                if text.strip():
                    st.session_state.extracted_text = text

                    # Initialize Gemini API
                    genai.configure(api_key=api_key)

                    # Setup AI Model with system instructions containing the notes
                    system_prompt = f"""
                    You are an expert college tutor. Use the following study notes to answer the student's questions. 
                    If the answer is not in the notes, use your general knowledge but mention that it wasn't in the provided document.

                    Notes:
                    {text[:60000]} # Limit to ~60k characters to avoid exceeding standard payload limits
                    """
                    model = genai.GenerativeModel('gemini-3-flash-preview', system_instruction=system_prompt)

                    # Start the chat session
                    st.session_state.chat_session = model.start_chat(history=[])
                    st.session_state.chat_history = []  # Reset UI chat
                    st.session_state.quiz_data = None  # Reset quiz

                    st.success("Document processed successfully! 🎉")
                else:
                    st.error("Could not extract any text from the document.")

