tab1, tab2 = st.tabs(["💬 Chat & Explain", "📝 Take a Quiz"])

# ------------------------------------------
# TAB 1: Chat Interface
# ------------------------------------------
with tab1:
    st.subheader("Chat with your Notes")
    if not st.session_state.chat_session:
        st.info("👈 Please enter your API key and upload a document in the sidebar to start chatting.")
    else:
        # Display previous chat history
        for msg in st.session_state.chat_history:
            with st.chat_message(msg["role"]):
                st.markdown(msg["content"])

        # Chat input box
        if prompt := st.chat_input("Ask a question about your notes... (e.g., 'Explain the second topic')"):
            # Show user message
            st.session_state.chat_history.append({"role": "user", "content": prompt})
            with st.chat_message("user"):
                st.markdown(prompt)

            # Get AI response
            with st.chat_message("assistant"):
                with st.spinner("Thinking..."):
                    try:
                        response = st.session_state.chat_session.send_message(prompt)
                        st.markdown(response.text)
                        st.session_state.chat_history.append({"role": "assistant", "content": response.text})
                    except Exception as e:
                        st.error(f"An error occurred: {e}")

# ------------------------------------------
# TAB 2: Quiz Generation
# ------------------------------------------
with tab2:
    st.subheader("Test Your Knowledge")
    if not st.session_state.extracted_text:
        st.info("👈 Please upload a document first to generate a quiz.")
    else:
        if st.button("Generate 5-Question Quiz 🚀"):
            with st.spinner("Analyzing notes and generating quiz..."):
                try:
                    genai.configure(api_key=api_key)
                    # We use a dedicated model instance for the quiz to keep generation clean
                    quiz_model = genai.GenerativeModel('gemini-3-flash-preview')

                    quiz_prompt = f"""
                    Analyze the following study notes and create a multiple-choice quiz with 5 questions to test understanding.
                    You MUST respond with ONLY a raw JSON array of objects. Do not include markdown formatting (like ```json).

                    Format exactly like this:
                    [
                      {{
                        "question": "Question text?",
                        "options": ["Option A", "Option B", "Option C", "Option D"],
                        "answer": "Option A",
                        "explanation": "Explanation of why Option A is correct."
                      }}
                    ]

                    Notes context:
                    {st.session_state.extracted_text[:40000]}
                    """
                    response = quiz_model.generate_content(quiz_prompt)
                    parsed_quiz = parse_quiz_json(response.text)

                    if parsed_quiz:
                        st.session_state.quiz_data = parsed_quiz
                        st.session_state.quiz_submitted = False
                        st.rerun()  # Refresh page to show the quiz
                except Exception as e:
                    st.error(f"Error generating quiz: {e}")

        # Display the generated quiz
        if st.session_state.quiz_data:
            st.markdown("---")
            with st.form("quiz_form"):
                user_answers = {}
                for i, q in enumerate(st.session_state.quiz_data):
                    st.markdown(f"**Q{i + 1}: {q['question']}**")
                    # Display options using radio buttons
                    user_answers[i] = st.radio("Select answer:", q['options'], key=f"q_{i}", index=None)
                    st.markdown("---")

                submitted = st.form_submit_button("Submit Answers")
                if submitted:
                    st.session_state.quiz_submitted = True

            # Calculate score and show explanations after submission
            if st.session_state.quiz_submitted:
                score = 0
                for i, q in enumerate(st.session_state.quiz_data):
                    if user_answers.get(i) == q['answer']:
                        score += 1

                st.success(f"### You scored {score} out of {len(st.session_state.quiz_data)}!")
                st.balloons()

                # Show detailed review
                st.subheader("Quiz Review:")
                for i, q in enumerate(st.session_state.quiz_data):
                    st.markdown(f"**Q{i + 1}: {q['question']}**")
                    user_ans = user_answers.get(i)
                    correct_ans = q['answer']

                    if user_ans == correct_ans:
                        st.success(f"Your answer: {user_ans} ✅")
                    else:
                        st.error(f"Your answer: {user_ans} ❌")
                        st.info(f"Correct answer: {correct_ans}")

                    st.caption(f"*Explanation:* {q['explanation']}")
                    st.markdown("---")