def extract_text_from_pdf(uploaded_file):
    """Extracts text from an uploaded PDF file."""
    text = ""
    try:
        pdf_reader = PyPDF2.PdfReader(uploaded_file)
        for page in pdf_reader.pages:
            extracted = page.extract_text()
            if extracted:
                text += extracted + "\n"
    except Exception as e:
        st.error(f"Error reading PDF: {e}")
    return text


def extract_text_from_ppt(uploaded_file):
    """Extracts text from an uploaded PPTX file."""
    text = ""
    try:
        prs = Presentation(uploaded_file)
        for slide in prs.slides:
            for shape in slide.shapes:
                if hasattr(shape, "text"):
                    text += shape.text + "\n"
    except Exception as e:
        st.error(f"Error reading PPTX: {e}")
    return text


def parse_quiz_json(response_text):
    """Safely extracts and parses JSON from the Gemini response."""
    try:
        # Find JSON array using regex in case the AI adds markdown like ```json
        match = re.search(r'\[.*\]', response_text, re.DOTALL)
        if match:
            return json.loads(match.group(0))
        return json.loads(response_text)
    except Exception as e:
        st.error("Failed to parse the quiz generated by AI. Please try generating again.")
        return None


